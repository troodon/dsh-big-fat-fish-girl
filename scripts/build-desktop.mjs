// Builds desktop/pet.html: a single self-contained page a native shell can load.
//
//   node scripts/build-desktop.mjs [--check]
//
// The page has no external references at all — no script tags, no stylesheets, no
// fonts — so a shell can load it from disk or from the plugin's own route without
// worrying about paths.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadEsbuild } from './esbuild-api.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')
const target = join(root, 'desktop', 'pet.html')

let esbuild
try {
  esbuild = loadEsbuild(root)
} catch (error) {
  const override = process.env.DSH_PLUGIN_ESBUILD
    ? ` from DSH_PLUGIN_ESBUILD=${JSON.stringify(process.env.DSH_PLUGIN_ESBUILD)}`
    : ''
  console.error(`Could not load the esbuild JavaScript API${override}: ${error.message}`)
  process.exit(1)
}

if (!esbuild) {
  if (checkOnly) {
    console.log('SKIP: esbuild is not installed — cannot verify desktop/pet.html here (npm install --no-save esbuild)')
    process.exit(0)
  }
  console.error('esbuild is needed to build the desktop page; install esbuild locally or set DSH_PLUGIN_ESBUILD to the path of its JavaScript API module (for example, node_modules/esbuild/lib/main.js).')
  process.exit(1)
}

let bundle
try {
  bundle = await esbuild.build({
    entryPoints: [join(root, 'desktop', 'pet-desktop.mjs')],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    write: false,
  })
} catch (error) {
  console.error(`esbuild failed while building desktop/pet.html: ${error.message}`)
  process.exit(1)
}

const page = `<!doctype html>
<!-- GENERATED by scripts/build-desktop.mjs from desktop/pet-desktop.mjs — do not edit. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Big Fat Fish Girl</title>
<style>html,body{margin:0;padding:0;background:transparent;overflow:hidden;width:100%;height:100%}</style>
</head>
<body>
<script>
${bundle.outputFiles[0].text}
</script>
<script>window.__BFFG_DESKTOP__ && window.__BFFG_DESKTOP__.start()</script>
</body>
</html>
`

if (checkOnly) {
  let current = null
  try { current = readFileSync(target, 'utf8') } catch {}
  if (current === page) {
    console.log('desktop/pet.html is up to date with desktop/pet-desktop.mjs')
    process.exit(0)
  }
  console.error('desktop/pet.html is stale — run: node scripts/build-desktop.mjs')
  process.exit(1)
}

writeFileSync(target, page)
console.log(`Built desktop/pet.html (${page.length} bytes)`)

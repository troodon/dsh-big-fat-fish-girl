// Per-skin data the browser needs, generated from the installed skins:
//   lib/animation/sheet-revisions.mjs  a content hash per atlas, so immutable URLs change with the PNG
//   lib/animation/skin-profiles.mjs    each skin's head anchors and gaze profile, from its skin.json
//
//   node scripts/build-skin-data.mjs [--check]
import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_MANIFEST } from '../lib/animation/manifest-defaults.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const skinsRoot = join(root, 'lib', 'skins')
const revisionsTarget = join(root, 'lib', 'animation', 'sheet-revisions.mjs')
const profilesTarget = join(root, 'lib', 'animation', 'skin-profiles.mjs')
const checkOnly = process.argv.includes('--check')
const sheets = Object.entries(DEFAULT_MANIFEST.sheets)
const files = [...new Set(sheets.map(([, sheet]) => sheet.file))].sort()

function installedSkinIds() {
  return readdirSync(skinsRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && statSync(join(skinsRoot, entry.name)).isDirectory())
    .map((entry) => entry.name)
    .sort((a, b) => a.localeCompare(b))
}

/** JSON with every numeric array on one line, so an anchor table reads as rows, not as a column. */
function literal(value) {
  return JSON.stringify(value, null, 2)
    .replace(/\[\s*\n\s*([^[\]{}]*?)\s*\]/g, (_, body) => `[${body.replace(/,\s*\n\s*/g, ', ')}]`)
}

function revisionsOf(skin) {
  const revisions = {}
  for (const file of files) {
    revisions[file] = createHash('sha256').update(readFileSync(join(skinsRoot, skin, file))).digest('hex')
  }
  return revisions
}

/**
 * One head anchor per row of every sheet. A skin whose data does not fit the manifest fails
 * here, at build time, instead of showing a bubble in the wrong place.
 */
function profileOf(skin) {
  const meta = JSON.parse(readFileSync(join(skinsRoot, skin, 'skin.json'), 'utf8'))
  const head = {}
  for (const [id, sheet] of sheets) {
    const anchors = meta.head?.[id]
    if (!Array.isArray(anchors) || anchors.length !== sheet.rows || anchors.some((value) => !Number.isFinite(value))) {
      throw new Error(`${skin}/skin.json: head.${id} needs ${sheet.rows} numeric anchors, one per row`)
    }
    head[id] = anchors
  }
  return { head, gaze: meta.gaze ?? null }
}

const skins = installedSkinIds()
const outputs = [
  [revisionsTarget, [
    '// GENERATED by scripts/build-skin-data.mjs — do not edit.',
    `export const SHEET_ASSET_REVISIONS = Object.freeze(${literal(Object.fromEntries(skins.map((skin) => [skin, revisionsOf(skin)])))})`,
    '',
  ].join('\n')],
  [profilesTarget, [
    '// GENERATED by scripts/build-skin-data.mjs from lib/skins/<id>/skin.json — do not edit.',
    `export const SKIN_PROFILES = Object.freeze(${literal(Object.fromEntries(skins.map((skin) => [skin, profileOf(skin)])))})`,
    '',
  ].join('\n')],
]

if (checkOnly) {
  const stale = outputs.filter(([target, generated]) => {
    let current = null
    try { current = readFileSync(target, 'utf8') } catch {}
    return current !== generated
  })
  if (stale.length === 0) {
    console.log('skin data matches the installed skins')
    process.exit(0)
  }
  for (const [target] of stale) console.error(`${relative(root, target)} is stale`)
  console.error('run: node scripts/build-skin-data.mjs')
  process.exit(1)
}

for (const [target, generated] of outputs) writeFileSync(target, generated)
console.log(`Updated skin data for ${skins.length} skins.`)

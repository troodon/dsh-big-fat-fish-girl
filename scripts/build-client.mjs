import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { loadEsbuild } from './esbuild-api.mjs'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const checkOnly = process.argv.includes('--check')
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
let esbuild
try {
  esbuild = loadEsbuild(root)
} catch (error) {
  const override = process.env.DSH_PLUGIN_ESBUILD
    ? ` from DSH_PLUGIN_ESBUILD=${JSON.stringify(process.env.DSH_PLUGIN_ESBUILD)}`
    : ''
  console.error(`Could not load the esbuild JavaScript API${override}: ${error.message}`)
  process.exit(1)
}
if (!esbuild) {
  if (checkOnly) {
    // Verification degrades loudly, not silently: the published package has no
    // devDependencies, so this check simply cannot run here.
    console.log('SKIP: esbuild is not installed — cannot verify lib/client.js here (npm install --no-save esbuild)')
    process.exit(0)
  }
  console.error('esbuild is needed only to rebuild the browser bundle; install esbuild locally or set DSH_PLUGIN_ESBUILD to the path of its JavaScript API module (for example, node_modules/esbuild/lib/main.js).')
  process.exit(1)
}

let build
try {
  build = await esbuild.build({
    entryPoints: [join(root, 'lib/web/client-entry.mjs')],
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: 'es2020',
    outfile: join(root, 'lib', '.client-build.tmp.js'),
    write: false,
  })
} catch (error) {
  console.error(`esbuild failed while building lib/client.js: ${error.message}`)
  process.exit(1)
}
const body = build.outputFiles[0].text.replace(/\n$/, '')
const wrapper = '// GENERATED by scripts/build-client.mjs from lib/web/client-entry.mjs — do not edit.\n'
  + 'window.__ModuleLoader__.load({\n'
  + '\tid: ' + JSON.stringify(pkg.name) + ',\n'
  + '\tfactory: (require) => {\n'
  + '\t\tvar module = { exports: {} };\n'
  + '\t\tvar exports = module.exports;\n'
  + body + '\n'
  + '\t\treturn module.exports;\n'
  + '\t}\n'
  + '});\n'
const target = join(root, 'lib/client.js')
if (checkOnly) {
  const current = readFileSync(target, 'utf8')
  if (current === wrapper) {
    console.log('lib/client.js is up to date with lib/web/client-entry.mjs')
    process.exit(0)
  }
  console.error('lib/client.js is stale — run: npm run build')
  process.exit(1)
}
writeFileSync(target, wrapper)
console.log('Built ' + pkg.name + ' browser module.')
